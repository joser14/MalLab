_NAME_RE = re.compile(r"^[A-Za-z0-9._-]+$")


def _safe_name(name: str) -> str:
    name = Path(name).name
    if not name.endswith((".yar", ".yara")):
        name += ".yar"
    if not _NAME_RE.match(name):
        raise ValueError("rule file name may only contain letters, digits, dot, dash, underscore")
    return name


# Strings too common in ordinary binaries to identify anything.
_BORING = re.compile(r"^(?:[A-Za-z]:\\Windows\\|kernel32|user32|ntdll|advapi32|msvcrt|mscoree|"
                     r"This program cannot be run in DOS mode|Microsoft|\.text|\.data|\.rdata|\.rsrc|"
                     r"GetProcAddress|LoadLibrary|ExitProcess|GetModuleHandle|[\W\d_]+$)", re.I)


def generate(static_report: dict, name_hint: str = "sample") -> str:
    """Draft a hunting rule from a static report: distinctive strings, embedded IOCs and the
    imphash. A starting point for an analyst to tune, not a finished signature."""
    st = static_report or {}
    sha = (st.get("hashes") or {}).get("sha256", "")
    rule = re.sub(r"\W", "_", f"MalLab_{name_hint}_{sha[:8]}").strip("_")
    if rule[0].isdigit():
        rule = "r_" + rule
    io = st.get("iocs") or {}
    picks = []
    for v in (io.get("urls") or [])[:4] + (io.get("domains") or [])[:4] + (io.get("ips") or [])[:3]:
        picks.append(v)
    strs = [s for s in (st.get("strings_sample") or []) if 8 <= len(s) <= 120 and not _BORING.search(s)]
    # Prefer longer, mixed-content strings: they're the least likely to appear in unrelated files.
    strs.sort(key=lambda s: (-len(set(s)), -len(s)))
    for s in strs:
        if len(picks) >= 12:
            break
        if s not in picks:
            picks.append(s)

    def lit(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    lines = [f"rule {rule}", "{", "    meta:",
             f'        description = "Auto-generated by MalLab from {sha[:16]}…; review before use"',
             f'        hash = "{sha}"', '        author = "MalLab draft"', "    strings:"]
    lines += [f"        $s{i} = {lit(s)} ascii wide nocase" for i, s in enumerate(picks)]
    imphash = (st.get("pe") or {}).get("imphash")
    is_pe = bool(st.get("pe"))
    cond = []
    if picks:
        cond.append(f"{max(1, min(3, len(picks) // 2))} of ($s*)")
    if imphash:
        cond.append(f'pe.imphash() == "{imphash}"')
    if not picks:
        lines.append('        $none = "MALLAB_NO_STRINGS"')
        cond.append("$none")
    header = ['import "pe"', ""] if imphash else []
    body = " or ".join(cond)
    lines += ["    condition:", f"        {'uint16(0) == 0x5A4D and ' if is_pe else ''}({body})", "}"]
    return "\n".join(header + lines) + "\n"


def ensure_starter(rules_dir: Path):
    rules_dir = Path(rules_dir)
    rules_dir.mkdir(parents=True, exist_ok=True)
    if any(rules_dir.glob("*.yar")) or any(rules_dir.glob("*.yara")):
        return
    for name, body in STARTER.items():
        (rules_dir / name).write_text(body.strip() + "\n", encoding="utf-8")


def list_rules(rules_dir: Path) -> list[dict]:
    rules_dir = Path(rules_dir)
    if not rules_dir.exists():
        return []
    out = []
    for f in sorted([*rules_dir.glob("*.yar"), *rules_dir.glob("*.yara")]):
        text = f.read_text(encoding="utf-8", errors="replace")
        out.append({"name": f.name, "size": f.stat().st_size,
                    "rule_count": len(re.findall(r"(?m)^\s*rule\s+\w+", text)),
                    "builtin": f.name in STARTER})
    return out


def read_rule(rules_dir: Path, name: str) -> str:
    p = Path(rules_dir) / _safe_name(name)
    if not p.exists():
        raise ValueError("no such rule file")
    return p.read_text(encoding="utf-8", errors="replace")


def write_rule(rules_dir: Path, name: str, text: str) -> dict:
    rules_dir = Path(rules_dir)
    rules_dir.mkdir(parents=True, exist_ok=True)
    name = _safe_name(name)
    # Validate by compiling when yara is available.
    try:
        import yara
        yara.compile(source=text)
    except ImportError:
        pass  # can't validate without yara-python; still allow saving
    except Exception as e:
        raise ValueError(f"rule does not compile: {e}")
    (rules_dir / name).write_text(text, encoding="utf-8")
    return {"name": name, "ok": True}


def delete_rule(rules_dir: Path, name: str):
    p = Path(rules_dir) / _safe_name(name)
    if p.exists():
        p.unlink()
